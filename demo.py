"""Try Upright without TikTok:  python demo.py

Pretends two users are live, using test video generated by ffmpeg:
  dual       a dual-layout live (a vertical AND a landscape stream)
  landscape  a landscape-only live
Anything else is "not live". Recordings go to ./demo-recordings.
"""
from __future__ import annotations

import http.server
import os
import random
import subprocess
import threading

os.environ.setdefault("RECORD_DIR", "demo-recordings")

import app  # noqa: E402  (must come after RECORD_DIR is set)
import tiktok  # noqa: E402

SIZES = {"/portrait.flv": (360, 640), "/landscape.flv": (640, 360)}
MEDIA_PORT = 0


def generator(w: int, h: int) -> list[str]:
    """An endless, real-time FLV test stream."""
    return [
        "ffmpeg", "-loglevel", "error",
        "-re", "-f", "lavfi", "-i", f"testsrc2=size={w}x{h}:rate=25",
        "-re", "-f", "lavfi", "-i", "sine=frequency=440:sample_rate=44100",
        "-c:v", "libx264", "-preset", "ultrafast", "-tune", "zerolatency", "-g", "50",
        "-pix_fmt", "yuv420p", "-b:v", "600k", "-c:a", "aac", "-b:a", "64k",
        "-f", "flv", "pipe:1",
    ]


class FakeCDN(http.server.BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.0"

    def do_GET(self) -> None:
        size = SIZES.get(self.path.split("?")[0])
        if not size:
            self.send_error(404)
            return
        self.send_response(200)
        self.send_header("Content-Type", "video/x-flv")
        self.end_headers()
        proc = subprocess.Popen(generator(*size), stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
        try:
            while True:
                chunk = proc.stdout.read1(16384)
                if not chunk:
                    break
                self.wfile.write(chunk)
                self.wfile.flush()
        except (BrokenPipeError, ConnectionResetError):
            pass
        finally:
            proc.kill()
            proc.wait()

    def log_message(self, *args) -> None:
        pass


async def fake_fetch_live(username: str, sessionid: str | None = None) -> tiktok.LiveInfo:
    name = username.lower()
    if name not in ("dual", "landscape"):
        raise tiktok.NotLive(f"@{username} isn't live right now. (Demo: try dual or landscape.)")
    base = f"http://127.0.0.1:{MEDIA_PORT}"
    streams = [tiktok.Stream(f"{base}/landscape.flv", "flv", "demo/landscape")]
    if name == "dual":
        streams.insert(0, tiktok.Stream(f"{base}/portrait.flv", "flv", "demo/portrait"))
    title = "Demo live, dual layout" if name == "dual" else "Demo live, landscape only"
    return tiktok.LiveInfo(username, "1", title, random.randint(20, 900), None, streams)


def main() -> None:
    global MEDIA_PORT
    cdn = http.server.ThreadingHTTPServer(("127.0.0.1", 0), FakeCDN)
    cdn.daemon_threads = True
    MEDIA_PORT = cdn.server_port
    threading.Thread(target=cdn.serve_forever, daemon=True).start()
    tiktok.fetch_live = fake_fetch_live
    print("\n  DEMO MODE: no TikTok involved. Type  dual  or  landscape  as the username.")
    app.main()


if __name__ == "__main__":
    main()
